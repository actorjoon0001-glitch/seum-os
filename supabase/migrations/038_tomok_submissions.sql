-- 038_tomok_submissions.sql
-- 외부 협력 건축사(토목건축사) 도면 업로드 메타데이터.
-- "부서별 업무 > 설계팀 > 토목건축사" 메뉴에서 PDF/DWG 도면을
-- 직접 업로드하면 설계팀 + 시공팀 전원에게 인앱/브라우저 알림이 발사된다.
-- 파일 자체는 Supabase Storage 'contract_files' 버킷의
-- 'tomok_submissions/...' 경로에 저장.
-- (036_pil_submissions.sql 과 동일 구조 — 외부 협력 건축사별 분리 테이블)

CREATE TABLE IF NOT EXISTS public.tomok_submissions (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  title text NOT NULL,
  description text,
  file_name text,
  file_url text,
  file_path text,
  file_size bigint,
  file_type text,
  contract_local_id text,
  uploaded_by_name text,
  design_manager text,
  uploaded_at timestamptz DEFAULT now(),
  is_deleted boolean DEFAULT false
);

COMMENT ON TABLE public.tomok_submissions IS '토목건축사(외부 협력) 도면 업로드 메타데이터.';
COMMENT ON COLUMN public.tomok_submissions.contract_local_id IS '연결된 계약 local_id (선택)';
COMMENT ON COLUMN public.tomok_submissions.file_url IS 'Supabase Storage public URL';
COMMENT ON COLUMN public.tomok_submissions.uploaded_by_name IS '업로드 주체 표시명 (토목건축사 본인 또는 대리 업로드자)';
COMMENT ON COLUMN public.tomok_submissions.design_manager IS '사내 설계 담당자명 (사내 팀원이 도면별로 기입)';

CREATE INDEX IF NOT EXISTS idx_tomok_submissions_uploaded_at
  ON public.tomok_submissions(uploaded_at DESC);
CREATE INDEX IF NOT EXISTS idx_tomok_submissions_contract
  ON public.tomok_submissions(contract_local_id);

ALTER TABLE public.tomok_submissions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "tomok_submissions_all_read" ON public.tomok_submissions;
CREATE POLICY "tomok_submissions_all_read"
  ON public.tomok_submissions FOR SELECT
  USING (true);

DROP POLICY IF EXISTS "tomok_submissions_all_write" ON public.tomok_submissions;
CREATE POLICY "tomok_submissions_all_write"
  ON public.tomok_submissions FOR ALL
  USING (true)
  WITH CHECK (true);

-- Realtime 활성화 (업로드 즉시 다른 세션 목록도 갱신)
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables
    WHERE pubname = 'supabase_realtime'
      AND schemaname = 'public'
      AND tablename = 'tomok_submissions'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.tomok_submissions;
  END IF;
END$$;
